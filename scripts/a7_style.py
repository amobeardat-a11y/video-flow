"""Code-drawn A7 study-room stage and fine-line rubber-hose character.

This is a local animation interpretation of the bundled A7 references, not a
claim that the frames were generated by the A7 video-model workflow.
"""

from __future__ import annotations

import copy
import math
import random
from functools import lru_cache

from PIL import Image, ImageDraw

from stickman_rig import StickmanPose, _round_stroke


INK = (29, 31, 28)
PAPER = (246, 245, 236)
SAGE = (202, 205, 188)
RED = (151, 88, 76)


def _line(draw: ImageDraw.ImageDraw, points, *, width=2, fill=INK):
    draw.line(points, fill=fill, width=width, joint="curve")


@lru_cache(maxsize=8)
def classroom_background(size: tuple[int, int], actor_left: bool) -> Image.Image:
    """A restrained 1930s classroom with a quiet acting zone and inked board."""
    w, h = size
    img = Image.new("RGB", size, SAGE)
    d = ImageDraw.Draw(img)
    sx, sy = w / 1280, h / 720
    def xy(x, y): return round(x * sx), round(y * sy)
    def box(x0, y0, x1, y1): return (*xy(x0, y0), *xy(x1, y1))
    line = max(1, round(2 * min(sx, sy)))

    # Broad matte paint regions and precise old-room joinery.
    d.rectangle(box(0, 0, 1280, 148), fill=(215, 216, 198))
    d.rectangle(box(0, 468, 1280, 611), fill=(222, 219, 199))
    d.rectangle(box(0, 611, 1280, 720), fill=(168, 163, 144))
    for y in (38, 49, 145, 468, 478, 609, 614):
        _line(d, [xy(0, y), xy(1280, y)], width=line, fill=(71, 73, 65))
    for x in range(40, 1280, 190):
        _line(d, [xy(x, 480), xy(x, 604)], width=line, fill=(107, 109, 97))
        _line(d, [xy(x + 5, 486), xy(x + 5, 598)], width=1, fill=(189, 187, 167))
    for y in (644, 680, 713):
        _line(d, [xy(0, y), xy(1280, y)], width=line, fill=(100, 98, 87))
    for x in range(70, 1280, 190):
        _line(d, [xy(x, 613), xy(x - 22, 720)], width=1, fill=(111, 108, 96))

    # A few hand-drawn seams, stipple marks, and restrained brick-red accents.
    rng = random.Random(701)
    for _ in range(760):
        x, y = rng.randrange(w), rng.randrange(round(h * .65))
        if y < round(h * .19):
            continue
        c = rng.choice(((185, 187, 173), (191, 193, 178), (213, 212, 194)))
        d.point((x, y), fill=c)
    for x, y in ((54, 136), (1228, 136), (54, 469), (1228, 469)):
        d.ellipse(box(x - 3, y - 3, x + 3, y + 3), fill=RED, outline=INK, width=1)

    # A framed slate board rather than modern floating cards.
    left, right = (604, 1234) if actor_left else (46, 676)
    d.rectangle(box(left - 12, 161, right + 12, 588), fill=(116, 105, 86), outline=INK, width=max(2, line))
    d.rectangle(box(left - 3, 170, right + 3, 578), fill=(80, 100, 85), outline=INK, width=line)
    for inset in (6, 10):
        d.rectangle(box(left - inset, 161 - inset, right + inset, 588 + inset), outline=(75, 69, 58), width=1)
    d.rectangle(box(left - 20, 588, right + 20, 601), fill=(111, 100, 82), outline=INK, width=line)
    for x in (left - 4, right + 4):
        d.ellipse(box(x - 3, 592, x + 3, 598), fill=RED, outline=INK, width=1)

    # A small clock gives the quiet acting zone a motivated moving prop.
    poster_x = 73 if actor_left else 1080
    d.rectangle(box(poster_x, 183, poster_x + 93, 281), fill=(233, 229, 208), outline=(62, 65, 58), width=line)
    d.ellipse(box(poster_x + 15, 196, poster_x + 72, 253), outline=(114, 118, 105), width=line)
    for dx, dy in ((0, -22), (22, 0), (0, 22), (-22, 0)):
        d.ellipse(box(poster_x + 43 + dx - 1, 224 + dy - 1, poster_x + 43 + dx + 1, 224 + dy + 1), fill=INK)
    return img


def draw_classroom_motion(image: Image.Image, size: tuple[int, int], actor_left: bool, t: float, beat_age: float) -> None:
    """Animate the wall clock and the chalk resting on the board tray."""
    w, h = size
    d = ImageDraw.Draw(image)
    sx, sy = w / 1280, h / 720
    def xy(x, y): return round(x*sx), round(y*sy)
    px = 73 if actor_left else 1080
    cx, cy = px + 43, 224
    minute = -math.pi/2 + t*.12
    second = -math.pi/2 + t*1.1
    _line(d, [xy(cx, cy), xy(cx + math.cos(minute)*15, cy + math.sin(minute)*15)], width=max(1, round(2*sx)), fill=INK)
    _line(d, [xy(cx, cy), xy(cx + math.cos(second)*23, cy + math.sin(second)*23)], width=max(1, round(2*sx)), fill=RED)
    d.ellipse((*xy(cx-2, cy-2), *xy(cx+2, cy+2)), fill=INK)
    pendulum_x = cx + math.sin(t*2.3)*8
    _line(d, [xy(cx, 253), xy(pendulum_x, 270)], width=max(1, round(2*sx)), fill=INK)
    d.ellipse((*xy(pendulum_x-3, 267), *xy(pendulum_x+3, 273)), fill=RED, outline=INK)

    board_left = 604 if actor_left else 46
    settle = math.exp(-max(0, beat_age)*5) * math.sin(max(0, beat_age)*16) * 8
    chalk_x = board_left + 47 + settle
    d.polygon([xy(chalk_x, 592), xy(chalk_x+30, 590), xy(chalk_x+32, 596), xy(chalk_x+2, 598)],
              fill=PAPER, outline=INK)
    if 0 <= beat_age < .4:
        for n in range(3):
            drift = beat_age * (9+n*3)
            x, y = xy(chalk_x + 12+n*6 + drift, 587 - n*3 - drift)
            d.ellipse((x-1, y-1, x+1, y+1), fill=(224, 224, 207))


def _draw_character(d: ImageDraw.ImageDraw, pose: StickmanPose, width: int, blink: bool):
    top, neck, head, _ = pose.compute_skeleton()
    hx, hy = head
    s = pose.scale
    fine = max(2, width)
    face_line = max(2, round(width * .85))
    detail = max(2, round(width * .52))

    # Legs, straight slim spine, and arms all remain connected to the rig.
    for leg in (pose.left_leg, pose.right_leg):
        if leg:
            _round_stroke(d, leg, INK, fine)
            fx, fy = leg[-1]
            _round_stroke(d, [(fx - 10*s, fy + 2*s), (fx, fy + 3*s), (fx + 10*s, fy + 1*s)], INK, max(3, round(5*s)))
    _round_stroke(d, [pose.hip, top, neck], INK, fine)
    for arm in (pose.left_arm, pose.right_arm):
        if arm:
            _round_stroke(d, arm, INK, fine)
            x, y = arm[-1]
            # White outlined mitten with a little thumb and two ink finger seams.
            r = 7.5*s
            d.ellipse((x-r, y-r*.75, x+r, y+r*.75), fill=(255, 255, 255), outline=INK, width=detail)
            d.ellipse((x-4*s, y+2*s, x+1*s, y+8*s), fill=(255, 255, 255), outline=INK, width=detail)
            _line(d, [(x+1*s, y-2*s), (x+1*s, y+3*s)], fill=INK, width=max(1, round(1.2*s)))
            _line(d, [(x+4*s, y-2*s), (x+4*s, y+2*s)], fill=INK, width=max(1, round(1.2*s)))

    r = pose.head_radius
    d.ellipse((hx-r, hy-r, hx+r, hy+r), fill=(255, 255, 255), outline=INK, width=face_line)
    # Exactly two individual curved hair tufts. Rotate their tips with the head.
    tilt = math.sin(math.radians(pose.head_tilt)) * 8*s
    _round_stroke(d, [(hx-7*s, hy-r+1*s), (hx-7*s+tilt, hy-r-13*s), (hx+1*s+tilt, hy-r-20*s)], INK, detail)
    _round_stroke(d, [(hx+1*s, hy-r+1*s), (hx+3*s+tilt, hy-r-11*s), (hx+14*s+tilt, hy-r-17*s)], INK, detail)

    # Oval eyes, tiny brows and a compact mouth preserve the approved identity.
    eye_y = hy - 4*s
    for sign in (-1, 1):
        ex = hx + sign * 15*s
        if blink:
            _round_stroke(d, [(ex-4*s, eye_y), (ex+4*s, eye_y)], INK, detail)
        else:
            d.ellipse((ex-3.6*s, eye_y-6.5*s, ex+3.6*s, eye_y+6.5*s), fill=INK)
            d.ellipse((ex-1.3*s, eye_y-4.5*s, ex+.3*s, eye_y-2.2*s), fill=(255, 255, 255))
    brow_y = hy - 23*s
    if pose.expression in {"worried", "sad"}:
        brows = [[(hx-25*s, brow_y+3*s), (hx-18*s, brow_y-3*s), (hx-11*s, brow_y)], [(hx+11*s, brow_y), (hx+18*s, brow_y-3*s), (hx+25*s, brow_y+3*s)]]
    elif pose.expression == "angry":
        brows = [[(hx-25*s, brow_y-5*s), (hx-18*s, brow_y-1*s), (hx-11*s, brow_y+4*s)], [(hx+11*s, brow_y+4*s), (hx+18*s, brow_y-1*s), (hx+25*s, brow_y-5*s)]]
    elif pose.expression == "surprised":
        brows = [[(hx-25*s, brow_y-8*s), (hx-18*s, brow_y-11*s), (hx-11*s, brow_y-8*s)], [(hx+11*s, brow_y-8*s), (hx+18*s, brow_y-11*s), (hx+25*s, brow_y-8*s)]]
    else:
        brows = [[(hx-24*s, brow_y), (hx-18*s, brow_y-4*s), (hx-12*s, brow_y)], [(hx+12*s, brow_y), (hx+18*s, brow_y-4*s), (hx+24*s, brow_y)]]
    for brow in brows:
        _round_stroke(d, brow, INK, detail)

    my = hy + 19*s
    if pose.expression == "smile":
        _round_stroke(d, [(hx-11*s, my-3*s), (hx, my+5*s), (hx+11*s, my-3*s)], INK, detail)
    elif pose.expression == "open":
        d.ellipse((hx-4*s, my-5*s, hx+4*s, my+7*s), outline=INK, width=detail)
    elif pose.expression in {"worried", "sad"}:
        _round_stroke(d, [(hx-10*s, my+5*s), (hx, my-3*s), (hx+10*s, my+5*s)], INK, detail)
    elif pose.expression == "surprised":
        d.ellipse((hx-4*s, my-5*s, hx+4*s, my+7*s), outline=INK, width=detail)
    elif pose.expression == "angry":
        _round_stroke(d, [(hx-9*s, my+2*s), (hx+9*s, my-1*s)], INK, detail)
    elif pose.expression == "think":
        _round_stroke(d, [(hx-7*s, my+1*s), (hx+8*s, my-2*s)], INK, detail)
    else:
        _round_stroke(d, [(hx-7*s, my), (hx+7*s, my)], INK, detail)


def draw_stickman_a7(image: Image.Image, pose: StickmanPose, *, width=4, time_seconds=0.0) -> None:
    """Antialias the character locally at 2× while preserving narrow ink lines."""
    top, neck, head, _ = pose.compute_skeleton()
    points = [pose.hip, top, neck, head]
    for limb in (pose.left_arm, pose.right_arm, pose.left_leg, pose.right_leg):
        if limb:
            points.extend(limb)
    margin = pose.head_radius + 30 * pose.scale
    left = max(0, math.floor(min(x for x, _ in points) - margin))
    top_y = max(0, math.floor(min(y for _, y in points) - margin))
    right = min(image.width, math.ceil(max(x for x, _ in points) + margin))
    bottom = min(image.height, math.ceil(max(y for _, y in points) + margin))
    if right <= left or bottom <= top_y:
        return
    factor = 2
    detail = copy.deepcopy(pose)
    detail.hip = ((pose.hip[0]-left)*factor, (pose.hip[1]-top_y)*factor)
    detail.scale *= factor
    for field in ("torso_len", "neck_len", "head_radius"):
        setattr(detail, field, getattr(detail, field) * factor)
    for field in ("arm_len", "leg_len"):
        setattr(detail, field, tuple(x*factor for x in getattr(detail, field)))
    for field in ("left_arm", "right_arm", "left_leg", "right_leg"):
        chain = getattr(pose, field)
        if chain:
            setattr(detail, field, [((x-left)*factor, (y-top_y)*factor) for x, y in chain])
    layer = Image.new("RGBA", ((right-left)*factor, (bottom-top_y)*factor), (0, 0, 0, 0))
    phase = time_seconds % 4.8
    _draw_character(ImageDraw.Draw(layer), detail, round(width*factor), 4.08 <= phase <= 4.22)
    small = layer.resize((right-left, bottom-top_y), Image.Resampling.LANCZOS)
    image.paste(small, (left, top_y), small)
